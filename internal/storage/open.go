type DB struct {
	sql                *sql.DB
	postgres           bool
	reconnectDirectory string
	pendingRejections  sync.Map // user ID to a confirmed rejection awaiting a durable write
	pendingUnblocks    sync.Map // TelegramUnblock events held when the journal is unavailable
}

func Open(ctx context.Context, path string) (*DB, error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return nil, fmt.Errorf("create SQLite directory: %w", err)
	}
	dsn := path + "?_pragma=foreign_keys(1)&_pragma=busy_timeout(5000)&_txlock=immediate&_time_format=sqlite"
	db, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, fmt.Errorf("open SQLite: %w", err)
	}
	db.SetMaxOpenConns(1)
	return open(ctx, &DB{sql: db, reconnectDirectory: path + ".reconnect"})
}

func OpenPostgres(ctx context.Context, dsn string) (*DB, error) {
	u, err := url.Parse(dsn)
	if err != nil || (u.Scheme != "postgres" && u.Scheme != "postgresql") || len(u.Path) < 2 {
		return nil, errors.New("DATABASE_URL must be a valid PostgreSQL URL")
	}
	parameters, err := url.ParseQuery(u.RawQuery)
	if err != nil {
		return nil, errors.New("DATABASE_URL contains invalid connection options")
	}
	if !parameters.Has("connect_timeout") {
		parameters.Set("connect_timeout", "5")
	}
	u.RawQuery = parameters.Encode()
	connector, err := pq.NewConnector(u.String())
	if err != nil {
		return nil, errors.New("DATABASE_URL contains invalid PostgreSQL connection options")
	}
	db := sql.OpenDB(connector)
	db.SetMaxOpenConns(5)
	db.SetMaxIdleConns(2)
	db.SetConnMaxIdleTime(5 * time.Minute)
	return open(ctx, &DB{sql: db, postgres: true})
}

func open(ctx context.Context, db *DB) (*DB, error) {
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	if err := db.sql.PingContext(ctx); err != nil {
		db.Close()
		if db.postgres {
			var pgErr *pq.Error
			if errors.As(err, &pgErr) {
				return nil, fmt.Errorf("connect to PostgreSQL (SQLSTATE %s)", pgErr.Code)
			}
			return nil, errors.New("could not connect to PostgreSQL; check DATABASE_URL and database availability")
		}
		return nil, fmt.Errorf("connect to SQLite: %w", err)
	}
	if err := db.Migrate(ctx); err != nil {
		db.Close()
		return nil, err
	}
	return db, nil
}

func (db *DB) Ping(ctx context.Context) error {
	return db.sql.PingContext(ctx)
}

func (db *DB) Close() error {
	return db.sql.Close()
}

func (db *DB) Migrate(ctx context.Context) error {
	tx, err := db.sql.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin storage migration: %w", err)
	}
	defer tx.Rollback()
	id, integer, timestamp := "INTEGER PRIMARY KEY", "INTEGER", "TIMESTAMP"
	if db.postgres {
		if _, err := tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock(hashtext('luxmed-watcher:storage:migration'))`); err != nil {
			return fmt.Errorf("lock PostgreSQL migration: %w", err)
		}
		id, integer, timestamp = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "BIGINT", "TIMESTAMPTZ"
	}
	ddl := fmt.Sprintf(schema, domain.WatchStatusActive, domain.WatchStatusPaused, domain.WatchStatusDeleted, id, integer, timestamp)
	if _, err := tx.ExecContext(ctx, ddl); err != nil {
		return fmt.Errorf("apply storage schema: %w", err)
	}
	if db.postgres {
		if _, err := tx.ExecContext(ctx, `
			ALTER TABLE luxmed_reconnect_delivery ADD COLUMN IF NOT EXISTS forbidden_failures INTEGER NOT NULL DEFAULT 0,
			    ADD COLUMN IF NOT EXISTS claim_id TEXT NOT NULL DEFAULT ''
		`); err != nil {
			return fmt.Errorf("add PostgreSQL reconnect delivery columns: %w", err)
		}
	} else {
		for _, column := range []struct{ table, name, definition string }{
			{"users", "preferred_city_id", "INTEGER"},
			{"users", "preferred_city_name", "TEXT NOT NULL DEFAULT ''"},
			{"luxmed_reconnect_delivery", "forbidden_failures", "INTEGER NOT NULL DEFAULT 0"},
			{"luxmed_reconnect_delivery", "claim_id", "TEXT NOT NULL DEFAULT ''"},
		} {
			var exists bool
			err := tx.QueryRowContext(ctx, `
				SELECT EXISTS (SELECT 1 FROM pragma_table_info($1) WHERE name=$2)
			`, column.table, column.name).Scan(&exists)
			if err != nil {
				return fmt.Errorf("inspect SQLite %s schema: %w", column.table, err)
			}
			if !exists {
				query := `ALTER TABLE ` + column.table + ` ADD COLUMN ` + column.name + ` ` + column.definition
				if _, err := tx.ExecContext(ctx, query); err != nil {
					return fmt.Errorf("add SQLite %s column %s: %w", column.table, column.name, err)
				}
			}
		}
		if err := migrateSQLiteAppointmentTimes(ctx, tx); err != nil {
			return fmt.Errorf("correct legacy SQLite appointment times: %w", err)
		}
	}
	if _, err := tx.ExecContext(ctx, `DELETE FROM luxmed_procedures WHERE is_recent = TRUE`); err != nil {
		return fmt.Errorf("remove private procedures from shared cache: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit storage migration: %w", err)
	}
	return nil
}

func migrateSQLiteAppointmentTimes(ctx context.Context, tx *sql.Tx) error {
	var version int
	if err := tx.QueryRowContext(ctx, `PRAGMA user_version`).Scan(&version); err != nil || version >= 1 {
		return err
	}
	// Earlier releases parsed Warsaw wall times as UTC and used the driver's Go Time.String encoding.
	rows, err := tx.QueryContext(ctx, `SELECT id, date_time FROM appointment_history WHERE date_time LIKE '% +0000 UTC'`)
	if err != nil {
		return err
	}
	defer rows.Close()
	type slot struct {
		id   int64
		when time.Time
	}
	var slots []slot
	for rows.Next() {
		var value slot
		if err := rows.Scan(&value.id, &value.when); err != nil {
			return err
		}
		slots = append(slots, value)
	}
	if err := rows.Err(); err != nil {
		return err
	}
	if len(slots) > 0 {
		warsaw, err := time.LoadLocation("Europe/Warsaw")
		if err != nil {
			return err
		}
		for _, slot := range slots {
			year, month, day := slot.when.Date()
			hour, minute, second := slot.when.Clock()
			when := time.Date(year, month, day, hour, minute, second, slot.when.Nanosecond(), warsaw)
			if _, err := tx.ExecContext(ctx, `UPDATE appointment_history SET date_time=$1 WHERE id=$2`, when, slot.id); err != nil {
				return err
			}
		}
	}
	_, err = tx.ExecContext(ctx, `PRAGMA user_version = 1`)
	return err
}
